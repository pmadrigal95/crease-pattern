// Builds src/styles/tokens.css and src/generated/tokens.json from the DTCG files in tokens/.
// Primitive color sets live per visual direction (tokens/directions/<id>.json) with a light
// and a dark group; base.json holds identity-independent tokens (type, space, radius, motion).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FALLBACK_DIRECTION } from './tokens-config.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function flatten(group, prefix = '') {
  const out = {};
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    const name = prefix ? `${prefix}-${kebab(key)}` : kebab(key);
    if (node && typeof node === 'object' && '$value' in node) out[name] = node.$value;
    else Object.assign(out, flatten(node, name));
  }
  return out;
}

const decl = (vars, prefix) =>
  Object.entries(vars)
    .map(([k, v]) => `  --${prefix}${k}: ${v};`)
    .join('\n');

const base = flatten(read('tokens/base.json'));
const directions = readdirSync(join(root, 'tokens/directions'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const json = read(`tokens/directions/${f}`);
    return { id: basename(f, '.json'), light: flatten(json.light), dark: flatten(json.dark) };
  });

const fallback = directions.find((d) => d.id === FALLBACK_DIRECTION);
if (!fallback) throw new Error(`Missing tokens for fallback direction "${FALLBACK_DIRECTION}"`);

const lightBlocks = directions
  .map((d) => `:root[data-direction='${d.id}'] {\n${decl(d.light, 'color-')}\n}`)
  .join('\n\n');
const darkMedia = directions
  .map(
    (d) =>
      `  :root[data-direction='${d.id}']:not([data-theme='light']) {\n${decl(d.dark, 'color-').replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }`,
  )
  .join('\n\n');
const darkForced = directions
  .map(
    (d) =>
      `:root[data-direction='${d.id}'][data-theme='dark'] {\n${decl(d.dark, 'color-')}\n  color-scheme: dark;\n}`,
  )
  .join('\n\n');

const css = `/* Generated by scripts/build-tokens.mjs. Do not edit: change tokens/*.json instead. */

:root {
${decl(base, '')}
${decl(fallback.light, 'color-')}
  /* Inspector box model, derived from each identity's palette. */
  --color-bm-margin: color-mix(in srgb, var(--color-earth) 34%, transparent);
  --color-bm-border: color-mix(in srgb, var(--color-mute) 45%, transparent);
  --color-bm-padding: color-mix(in srgb, var(--color-second) 30%, transparent);
  --color-bm-content: color-mix(in srgb, var(--color-accent-ui) 26%, transparent);
}

${lightBlocks}

@media (prefers-color-scheme: dark) {
${darkMedia}
}

${darkForced}
`;

const manifest = {
  generatedFrom: 'tokens/',
  base,
  directions: Object.fromEntries(directions.map((d) => [d.id, { light: d.light, dark: d.dark }])),
};

mkdirSync(join(root, 'src/styles'), { recursive: true });
mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'src/styles/tokens.css'), css);
writeFileSync(join(root, 'src/generated/tokens.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`tokens: ${directions.length} directions, ${Object.keys(base).length} base tokens`);
